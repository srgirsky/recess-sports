// The neighborhood. 30 kids you can draft from — World 1's cast.
//
// This file is CONTENT, not logic — rebalance kids freely. The cast sheet is
// `docs/world1/kids-roster-v0.7.md`: seven Tier 1 heroes and twenty-three
// Tier 2 neighborhood kids over ten archetypes, fifteen girls and fifteen boys.
// Each kid's `archetype` and `tier` come from that sheet; a kid's hook is a
// habit or a flaw, never a heritage, and identity lives only in a name, a face
// and something visible.
//
// ★ THE IDS ARE SLOTS, NOT NAMES. In November 2026 the cast was re-cast in
// place: every kid kept the id of the slot it took over (`calls_shot` is Mars,
// `wheelchair_ace` is Dev), because the id is the pick-tally key, the album
// key, the model filename and the registry key, and forty-six files hang on
// it. `recast.was` says who held the slot; `recast.modelCarries` says whether
// the delivered v2 sculpt is still a credible stand-in for the new kid (a boy's
// body is not a stand-in for a girl, so those slots draw the proxy until a
// sculpt against the new sheet lands). New parts the sheet calls for — the
// sport hijab, the patka, tzitzit, catcher's gear, the racing chair — are not
// in the art kit yet; the nearest existing part stands in and is noted.
//
// Stats are 1-10. Aim for real trade-offs: sluggers can't run, speedsters
// can't hit for power, a few kids are weak-but-adorable, etc. The `visual`
// block drives the flat-mascot art (expression/hair/body/uniform/accessory).
// `voiceGender` (required) matches the kid's spoken voice to who they are —
// it picks the gendered curated-voice sublist + pitch band in systems/voices.ts.
// `draftLine` is the kid's own excited shout when picked (spoken in their
// derived voice — systems/voices.ts); `chatterLines` are optional signature
// field-chatter lines for the personality-forward kids (systems/chatter.ts
// has generic pools for everyone else). Ability hooks are data-driven, and so
// is `quirk` — the kid's signature behaviour in the classic game, whose rules
// live in `systems/quirks.ts`. The mechanics the sheet describes that are NOT
// built yet (Heater, Brick House, the fence arms, the sibling bonus) are
// listed in `docs/world1/cast-scope.md`.
// ---------------------------------------------------------------------------

